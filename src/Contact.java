/**
 * Contact.java
 * Model class that represents a single contact.
 * Uses encapsulation: all fields are private and accessed through getters and setters.
 */
public class Contact {

    private int id;          // Auto-generated by the database
    private String name;
    private String email;
    private String mobile;

    /** Constructor used when creating a NEW contact (id is not known yet). */
    public Contact(String name, String email, String mobile) {
        this.name = name;
        this.email = email;
        this.mobile = mobile;
    }

    /** Constructor used when reading an EXISTING contact from the database. */
    public Contact(int id, String name, String email, String mobile) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.mobile = mobile;
    }

    // ---------- Getters ----------
    public int getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    public String getMobile() {
        return mobile;
    }

    // ---------- Setters ----------
    public void setId(int id) {
        this.id = id;
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public void setMobile(String mobile) {
        this.mobile = mobile;
    }

    @Override
    public String toString() {
        return "Contact{id=" + id + ", name='" + name + "', email='" + email + "', mobile='" + mobile + "'}";
    }
}
